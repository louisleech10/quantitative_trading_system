#!/usr/bin/env bash
# plain_docs_shape_check.sh — 白話核心檔之「形狀」機械閘（PLAINDOCS，2026-09-20）
#
# 出生理由（使用者 2026-09-20 第三、四次指出，逐字）：
#   「白話文檔亂七八糟，超多檔案，檔名多到難找，也無法分辨。也不知道現在在做什麼，
#     要去看哪一份，看文檔中的哪一部份。內文也流水帳，根本找不到最後結論是什麼。
#     想要知道有哪些項目還沒做也不知去哪找，然後新增越來越多，又交叉變更，一堆新舊不分」
#   ＋「我連做過哪些都找不到」
#
# 實測病徵（2026-09-20）：26 份、17,549 行；`GAP-3施工進度.md` 2,407 行內含「第 1 輪」～
#   「第 29 輪」之審查流水帳；「還沒做的事」散在五個來源、沒有一個是全的；
#   「做過什麼」**沒有任何一份負責**。
#
# 根因不是檔案多，是**文檔模型錯**：一票一檔、每次進展往上疊一條 ⇒
#   檔數隨票數線性成長、結論被埋、無失效機制、無跨票視角。
#
# ──────────────────────────────────────────────────────────────────────
# 🔴 **v2 改為白名單（首版是黑名單，被使用者當場打穿）**
#
#   首版判準＝「行首出現 `> 📌` 或 `> 🏁` 即為流水帳」。使用者逐字：
#     「出現標記你這什麼爛方式，換個圖示不就繞過了 完全是敷衍」——**正確**。
#   那是黑名單，換一個 emoji、改成 `-` 開頭、或不加引用符號即可繞過。
#   且此舉**違反主委自己記錄在案的規則**（2026-08-07 使用者定死，亦見
#   `plain_docs_order_check.sh` 檔頭）：「遇散文／關鍵字判斷一律改**封閉可導出集合**
#   的機械閘，黑名單永遠列不完」。
#
#   v2 之封閉集合＝**章節標題白名單 ＋ 行數上限**，兩者皆與「用什麼符號」無關：
#     · 想加一條流水帳，內容只能去兩個地方——**開新章節**或**撐大既有章節**。
#     · 開新章節 ⇒ 撞標題白名單（固定三檔）或章節數上限（結論書）。
#     · 撐大既有章節 ⇒ 撞行數上限。
#   ⇒ **換圖示不再有任何作用**；符號完全不在判準內。
# ──────────────────────────────────────────────────────────────────────
#
# 誠實邊界（勿宣稱超出）：
#   1. 只驗形狀，**不驗內容是否真的是結論**——可以在既有章節內寫一段散文式流水帳，
#      只要不超行數就過。⇒ 本閘擋「累積」，不擋「一次寫爛」。後者交審查。
#   2. `git commit --no-verify` 可繞過。
#   3. 改章節標題白名單本身可放寬本閘——但那是**改檔案**、進 diff、會被看到，
#      與「換個圖示」這種無痕繞過不同。
#
# 用法：bash scripts/plain_docs_shape_check.sh [檔案…]（預設掃四類核心檔）
# rc=0 全部合規；rc=1 有違規（逐條列出）。
set -u
cd "$(dirname "$0")/.." || exit 2
DIR="白話說明"

# ── 封閉集合①：三份固定核心檔之章節標題（逐字全等，順序不拘）────────────
_allowed_sections_for() {
  case "$1" in
    "現在做到哪.md")
      printf '%s\n' "現在在做" "做到哪" "要你決定嗎" "卡住嗎" "下一件事" ;;
    "還沒做的事.md")
      printf '%s\n' "一、會影響你現在能不能用（優先）" "二、排定順序的票" \
                    "三、待觸發（條件沒到就不做，不是拖延）" \
                    "四、技術殘留（你不會看到，我自己追）" "五、這份怎麼維護" ;;
    "做過什麼.md")
      printf '%s\n' "量化主線" "治理線（2026-08-14 起停止擴建）" \
                    "方向重定（做了但不算交付）" "這份怎麼維護" ;;
    *) : ;;
  esac
}

# ── 封閉集合②：行數上限與章節數上限 ──────────────────────────────────
_line_limit_for() {
  case "$1" in
    "現在做到哪.md")  echo 80  ;;   # 只有現在，不該長
    "還沒做的事.md")  echo 150 ;;   # 做完刪行，不該長
    "做過什麼.md")    echo 400 ;;   # 唯一允許累積者
    *結論.md)          echo 200 ;;   # 只寫結論，不寫過程
    *)                 echo 0   ;;   # 不在管轄範圍
  esac
}
# 結論書之章節不逐字固定（各票要講的真問題不同），改以**章節數上限**收束。
_section_limit_for() {
  case "$1" in
    *結論.md) echo 6 ;;
    *)         echo 0 ;;
  esac
}

files=("$@")
if [ "${#files[@]}" -eq 0 ]; then
  files=()
  for f in "${DIR}"/現在做到哪.md "${DIR}"/還沒做的事.md "${DIR}"/做過什麼.md "${DIR}"/*結論.md; do
    [ -f "${f}" ] && files+=("${f}")
  done
fi
[ "${#files[@]}" -gt 0 ] || { echo "[shape_check] 無核心檔可查（略過）"; exit 0; }

bad=0
for f in "${files[@]}"; do
  name="$(basename "${f}")"
  limit="$(_line_limit_for "${name}")"
  [ "${limit}" -gt 0 ] || continue

  # ① 章節標題白名單（三份固定檔）
  allowed="$(_allowed_sections_for "${name}")"
  if [ -n "${allowed}" ]; then
    while IFS= read -r h; do
      [ -n "${h}" ] || continue
      if ! printf '%s\n' "${allowed}" | grep -qxF "${h}"; then
        echo "[shape_check] ✗ ${f}：章節「${h}」不在白名單" >&2
        echo "    本檔只回答一個問題，章節是封閉集合。要新增章節＝改本腳本之白名單（會進 diff）。" >&2
        bad=1
      fi
    done <<EOF
$(sed -n 's/^## //p' "${f}")
EOF
    # 缺章節也要報——否則可以把整段刪掉規避行數上限
    while IFS= read -r want; do
      [ -n "${want}" ] || continue
      grep -qxF "## ${want}" "${f}" || {
        echo "[shape_check] ✗ ${f}：缺必要章節「${want}」" >&2
        bad=1
      }
    done <<EOF
${allowed}
EOF
  fi

  # ② 章節數上限（結論書）
  slimit="$(_section_limit_for "${name}")"
  if [ "${slimit}" -gt 0 ]; then
    n_sec="$(grep -c '^## ' "${f}" 2>/dev/null || true)"
    if [ "${n_sec}" -gt "${slimit}" ]; then
      echo "[shape_check] ✗ ${f}：${n_sec} 個章節，超過上限 ${slimit}" >&2
      echo "    結論書只寫結論。過程放 git log 與 handoffs/reconcile/ 之收斂檔。" >&2
      bad=1
    fi
  fi

  # ③ 行數上限（所有核心檔）
  n_line="$(wc -l < "${f}" | tr -d ' ')"
  if [ "${n_line}" -gt "${limit}" ]; then
    echo "[shape_check] ✗ ${f}：${n_line} 行，超過上限 ${limit} 行" >&2
    echo "    又開始堆積了。把過程移去結論書或 git log，本檔只留它負責回答的那一個問題。" >&2
    bad=1
  fi
done

if [ "${bad}" -eq 0 ]; then
  echo "[shape_check] ✓ 核心檔形狀合規（檢查 ${#files[@]} 檔：章節白名單＋章節數／行數上限）"
  exit 0
fi
exit 1
