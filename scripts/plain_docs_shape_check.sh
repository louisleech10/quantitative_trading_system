#!/usr/bin/env bash
# plain_docs_shape_check.sh — 白話核心檔之「形狀」機械閘（PLAINDOCS，2026-09-20）
#
# 出生理由（使用者 2026-09-20 第三次指出，逐字）：
#   「白話文檔亂七八糟，超多檔案，檔名多到難找，也無法分辨。也不知道現在在做什麼，
#     要去看哪一份，看文檔中的哪一部份。內文也流水帳，根本找不到最後結論是什麼。
#     想要知道有哪些項目還沒做也不知去哪找，然後新增越來越多，又交叉變更，一堆新舊不分」
#   ＋「我連做過哪些都找不到」
#
# 實測病徵（2026-09-20）：26 份、17,549 行；`GAP-3施工進度.md` 2,407 行內含「第 1 輪」～
#   「第 29 輪」之審查流水帳；「還沒做的事」散在五個來源、沒有一個是全的；
#   「做過什麼」**沒有任何一份負責**。
#
# 根因不是檔案多，是**文檔模型錯**：一票一檔、每次進展往上疊一條 ⇒
#   檔數隨票數線性成長、結論被埋、無失效機制、無跨票視角。
#
# 為何是機械閘而非紀律：疊加是**最省事的編輯方式**（Edit 必須錨定既有文字，
#   最省事的錨點就是開頭）。與自制力無關，同 `plain_docs_order_check.sh` 之出生理由。
#
# 本閘只檢查**形狀**，不做語意判斷；判準為封閉可列舉集合：
#   ① 四類核心檔（現在做到哪／還沒做的事／做過什麼／*結論.md）**不得含流水帳標記**
#      （行首 `> 📌` 或 `> 🏁` — 那是「往上疊一條」的字面形態）
#   ② 四類核心檔各有行數上限——超過即表示又開始堆積
#   ③ `做過什麼.md` 為唯一允許累積者，故其上限較寬
#
# 誠實邊界（勿宣稱超出）：
#   1. 只驗形狀，**不驗內容是否真的是結論**——可以寫一份沒有流水帳標記的流水帳。
#   2. `git commit --no-verify` 可繞過。
#   ⇒ 屬「擋意外不防蓄意」，與本 repo 既有機檢同級。
#
# 用法：bash scripts/plain_docs_shape_check.sh [檔案…]（預設掃四類核心檔）
# rc=0 全部合規；rc=1 有違規（逐條列出）。
set -u
cd "$(dirname "$0")/.." || exit 2
DIR="白話說明"

_limit_for() {
  case "$1" in
    "現在做到哪.md")  echo 80  ;;   # 只有現在，不該長
    "還沒做的事.md")  echo 150 ;;   # 做完刪行，不該長
    "做過什麼.md")    echo 400 ;;   # 唯一允許累積者
    *結論.md)          echo 200 ;;   # 只寫結論，不寫過程
    *)                 echo 0   ;;   # 不在管轄範圍
  esac
}

files=("$@")
if [ "${#files[@]}" -eq 0 ]; then
  files=()
  for f in "${DIR}"/現在做到哪.md "${DIR}"/還沒做的事.md "${DIR}"/做過什麼.md "${DIR}"/*結論.md; do
    [ -f "${f}" ] && files+=("${f}")
  done
fi

[ "${#files[@]}" -gt 0 ] || { echo "[shape_check] 無核心檔可查（略過）"; exit 0; }

bad=0
for f in "${files[@]}"; do
  name="$(basename "${f}")"
  limit="$(_limit_for "${name}")"
  [ "${limit}" -gt 0 ] || continue

  # ① 流水帳標記
  n_log="$(grep -c '^> 📌\|^> 🏁' "${f}" 2>/dev/null || true)"
  if [ "${n_log}" -gt 0 ]; then
    echo "[shape_check] ✗ ${f}：含 ${n_log} 條流水帳標記（行首 '> 📌' 或 '> 🏁'）" >&2
    echo "    核心檔不得往上疊條目。現況改整段覆蓋／做完刪行／結論書只寫結論。" >&2
    grep -n '^> 📌\|^> 🏁' "${f}" | head -3 | sed 's/^/      /' >&2
    bad=1
  fi

  # ② 行數上限
  n_line="$(wc -l < "${f}" | tr -d ' ')"
  if [ "${n_line}" -gt "${limit}" ]; then
    echo "[shape_check] ✗ ${f}：${n_line} 行，超過上限 ${limit} 行" >&2
    echo "    又開始堆積了。把過程移去結論書或 git log，本檔只留該檔負責回答的那一個問題。" >&2
    bad=1
  fi
done

if [ "${bad}" -eq 0 ]; then
  echo "[shape_check] ✓ 核心檔形狀合規（檢查 ${#files[@]} 檔：無流水帳標記、未超行數上限）"
  exit 0
fi
exit 1
